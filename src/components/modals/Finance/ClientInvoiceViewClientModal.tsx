import React, { useState, useEffect } from "react";
import Modal from "../../ui/Modal";
import {
  getClientInvoiceByCompanyApi,
  type CompanyClientInvoiceData,
} from "../../../api/financeApi/clientInvoiceApi";
import { toast } from "react-toastify";
import Select from "../../ui/Select";
import { StatusBadge } from "../../ui/StatusBadge";
import { ChevronLeft, ChevronRight } from "lucide-react";

// FIXED: Import the timezone formatter so Created At renders consistently
import { formatDateTime } from "../../../helper/dateFormatter";

interface ClientInvoiceViewClientModalProps {
  isOpen: boolean;
  onClose: () => void;
  companyName: string | null;
  companyInvoiceId: number | null;
}

const rowsOptions = [
  { value: "10", label: "10" },
  { value: "25", label: "25" },
  { value: "50", label: "50" },
  { value: "100", label: "100" },
];

